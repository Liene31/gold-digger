const priceDisplaySpan = document.getElementById("price-display");
const investmentAmountInput = document.getElementById("investment-amount");
const investNowBtn = document.getElementById("invest-btn");
const connectionStatusPara = document.getElementById("connection-status");
const dialog = document.getElementById("dialog");
const closeDialogBtn = document.getElementById("close-dialog");
let investmentSummaryPara = document.getElementById("investment-summary");

let price = 0;

function displayRandomPrice(price) {
  priceDisplaySpan.textContent = price;
}

async function fetchPrices() {
  try {
    const response = await fetch("/api");
    price = await response.json();
    displayRandomPrice(price);
    connectionStatusPara.textContent = "Live Price 🟢";
  } catch (err) {
    console.error(err);
    priceDisplaySpan.textContent = "----.--";
    connectionStatusPara.textContent = "Disconnected 🔴";
  }
}

investNowBtn.addEventListener("click", async (e) => {
  e.preventDefault();
  const inputValue = investmentAmountInput.value;

  const payload = {
    amountPaid: inputValue,
    pricePerOz: price,
  };

  try {
    const response = await fetch("/api", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify(payload),
    });
    // The server responded, but with an HTTP error
    // There was a response from the back
    // DB error, bad request, or something else
    // these parts stays in try block and are not caught in the catch block
    // when the network is down and server is not reachable backend can't send any response and that goes directly to the catch block
    if (!response.ok) {
      if (response.status === 500) {
        console.log("Server/database error");
      } else if (response.status === 400) {
        console.log("Bad request");
      } else {
        console.log(`HTTP error: ${response.status}`);
      }
      return;
    }

    // Successful response
    const data = await response.json();
    const ozt = data.amountPaid / data.pricePerOz;
    displayDialog(data.amountPaid, ozt.toFixed(2));
    investmentAmountInput.value = "";
  } catch (err) {
    // fetch itself failed — no valid HTTP response was received
    console.log("Network error or server unreachable");
    // an error generated by the browser/JavaScript environment because the network request failed
    console.error(err);
  }
});

closeDialogBtn.addEventListener("click", () => {
  dialog.style.display = "none";
});

function setIntervalAndExecute(fn, time) {
  fn();
  return setInterval(fn, time);
}

function displayDialog(amountPaid, ozt) {
  dialog.style.display = "block";
  investmentSummaryPara.textContent = `You just bought ${ozt} ounces (ozt) for £${amountPaid}. \n You will receive documentation shortly.`;
}

setIntervalAndExecute(fetchPrices, 3000);
